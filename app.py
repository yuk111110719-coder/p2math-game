def run_math_challenge():
    print("--- 小二數學挑戰賽（升級版） ---")
    print("家長好！我係你嘅數學小幫手，今次已經幫你清理咗重複題目，仲修正咗答案添！\n")
    
    # 決定這次要玩幾題（預設最多抽 10 題或取全部題庫的數量，確保不重複）
    total_rounds = min(10, len(question_bank))
    
    # 使用 random.sample 隨機抽出不重複的題目清單
    selected_questions = random.sample(question_bank, total_rounds)
    
    score = 0
    
    for index, q_item in enumerate(selected_questions, 1):
        user_ans = input(f"第 {index} 題: {q_item['q']} \n答案係: ").strip()
        
        if user_ans == q_item['a']:
            print("答啱咗！好叻女呀！\n")
            score += 1
        else:
            print(f"唔好灰心，正確答案係 {q_item['a']}，下次繼續努力！\n")
            
        # 當完成一半或全部指定題數時觸發鼓勵
        if index in [5, total_rounds]:
            print("----------------------------")
            print(random.choice(encouragements))
            print("----------------------------\n")
            
    print(f"挑戰結束！你一共答啱咗 {score} / {total_rounds} 題！")

if __name__ == "__main__":
    run_math_challenge()
